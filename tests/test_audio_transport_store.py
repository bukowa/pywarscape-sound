def test_audio_transport_store_initial_state():
    store = AudioTransportStore()
    assert store.state.status == PlaybackStatus.IDLE
    assert store.state.active_track is None
    assert store.state.auto_play is True
    assert store.state.loop is False
    assert store.state.volume == VolumeRatio(1.0)


def test_audio_transport_store_subscription():
    store = AudioTransportStore()
    observed: list[TransportState] = []

    unsub = store.subscribe(observed.append)

    store.toggle_auto_play()
    assert len(observed) == 1
    assert observed[0].auto_play is False

    store.toggle_loop()
    assert len(observed) == 2
    assert observed[1].loop is True

    unsub()
    store.set_volume(0.5)
    assert len(observed) == 2  # No new notification after unsub


def test_audio_transport_store_select_none_clears_track():
    store = AudioTransportStore()
    track = AudioTrack(
        source_id=AudioSourceId(1),
        title="test.wem",
        file_path="audio/test.wem",
    )
    store.select_track(track)
    # auto_play is True, but file doesn't exist, so error recorded or ready
    assert store.state.active_track is not None or store.state.error_message is not None

    store.select_track(None)
    assert store.state.active_track is None
    assert store.state.status == PlaybackStatus.IDLE


def test_audio_transport_store_playback_with_silent_pcm():
    pcm_bytes = build_silent_pcm_wem_bytes(duration_ms=500, sample_rate=32000)
    track = AudioTrack(
        source_id=AudioSourceId(999),
        title="silent_pcm.wem",
        embedded_bytes=pcm_bytes,
        duration_ms=Millisecond(500),
    )

    store = AudioTransportStore()
    store.select_track(track)

    # With auto_play=True and valid PCM bytes, should transition to PLAYING
    assert store.state.status == PlaybackStatus.PLAYING
    assert store.state.active_track is not None
    assert store.state.error_message is None

    # Pause
    store.pause()
    assert store.state.status == PlaybackStatus.PAUSED

    # Resume (play)
    store.play()
    assert store.state.status == PlaybackStatus.PLAYING

    # Stop
    store.stop()
    assert store.state.status == PlaybackStatus.READY
    assert store.state.position_ms == Millisecond(0)


