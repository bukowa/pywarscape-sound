def test_selecting_track_while_playing_halts_previous_track_single_busy_channel():
    import pygame

    pcm_bytes1 = build_silent_pcm_wem_bytes(duration_ms=2000, sample_rate=32000)
    pcm_bytes2 = build_silent_pcm_wem_bytes(duration_ms=2000, sample_rate=32000)

    track1 = AudioTrack(
        source_id=AudioSourceId(101),
        title="track1.wem",
        embedded_bytes=pcm_bytes1,
        duration_ms=Millisecond(2000),
    )
    track2 = AudioTrack(
        source_id=AudioSourceId(102),
        title="track2.wem",
        embedded_bytes=pcm_bytes2,
        duration_ms=Millisecond(2000),
    )

    store = AudioTransportStore()
    assert store.state.auto_play is True

    # 1. Start track 1
    store.select_track(track1)
    assert store.state.status == PlaybackStatus.PLAYING
    assert store.state.active_track.source_id == AudioSourceId(101)
    busy_count_1 = sum(
        1 for i in range(pygame.mixer.get_num_channels()) if pygame.mixer.Channel(i).get_busy()
    )
    assert busy_count_1 == 1

    # 2. Select track 2 while track 1 is playing -> halts track 1, plays track 2
    store.select_track(track2)
    assert store.state.status == PlaybackStatus.PLAYING
    assert store.state.active_track.source_id == AudioSourceId(102)
    busy_count_2 = sum(
        1 for i in range(pygame.mixer.get_num_channels()) if pygame.mixer.Channel(i).get_busy()
    )
    assert busy_count_2 == 1

    store.stop()


def test_selecting_track_with_autoplay_false_halts_previous_playback_zero_busy_channels():
    import pygame

    pcm_bytes1 = build_silent_pcm_wem_bytes(duration_ms=2000, sample_rate=32000)
    pcm_bytes2 = build_silent_pcm_wem_bytes(duration_ms=2000, sample_rate=32000)

    track1 = AudioTrack(
        source_id=AudioSourceId(201),
        title="track1.wem",
        embedded_bytes=pcm_bytes1,
        duration_ms=Millisecond(2000),
    )
    track2 = AudioTrack(
        source_id=AudioSourceId(202),
        title="track2.wem",
        embedded_bytes=pcm_bytes2,
        duration_ms=Millisecond(2000),
    )

    store = AudioTransportStore()
    store.select_track(track1)
    assert store.state.status == PlaybackStatus.PLAYING
    assert pygame.mixer.get_busy() is True

    # Toggle auto_play off while playing track 1
    store.toggle_auto_play()
    assert store.state.auto_play is False
    assert store.state.status == PlaybackStatus.PLAYING

    # Selecting track 2 with auto_play=False must completely halt playback
    store.select_track(track2)
    assert store.state.status == PlaybackStatus.READY
    assert store.state.active_track.source_id == AudioSourceId(202)
    assert store.state.position_ms == Millisecond(0)
    assert pygame.mixer.get_busy() is False

    busy_channels = sum(
        1 for i in range(pygame.mixer.get_num_channels()) if pygame.mixer.Channel(i).get_busy()
    )
    assert busy_channels == 0

    store.stop()


def test_duration_measurement_notifies_listeners():
    pcm_bytes = build_silent_pcm_wem_bytes(duration_ms=800, sample_rate=32000)
    # Track with 0 initial duration
    track = AudioTrack(
        source_id=AudioSourceId(301),
        title="unmeasured.wem",
        embedded_bytes=pcm_bytes,
        duration_ms=Millisecond(0),
    )

    store = AudioTransportStore()
    observed_durations: list[int] = []

    def on_state(s: TransportState) -> None:
        if s.active_track:
            observed_durations.append(int(s.active_track.duration_ms))

    store.subscribe(on_state)
    store.select_track(track)

    assert store.state.status == PlaybackStatus.PLAYING
    # Measured duration must be non-zero and reflected in notifications
    assert int(store.state.active_track.duration_ms) > 0
    assert any(dur > 0 for dur in observed_durations)

    store.stop()


def test_tick_loop_wraps_elapsed_ms():
    import time

    pcm_bytes = build_silent_pcm_wem_bytes(duration_ms=500, sample_rate=32000)
    track = AudioTrack(
        source_id=AudioSourceId(401),
        title="loop_test.wem",
        embedded_bytes=pcm_bytes,
        duration_ms=Millisecond(500),
    )

    store = AudioTransportStore()
    store.toggle_loop()
    assert store.state.loop is True

    store.select_track(track)
    assert store.state.status == PlaybackStatus.PLAYING

    # Simulate 1200 ms elapsed with dur_ms = 500
    store._play_start_time = time.monotonic() - 1.2
    store.tick()

    # 1200 % 500 = 200 ms (allowing small jitter in monotonic clock)
    assert 150 <= int(store.state.position_ms) <= 250

    # Toggle loop off: must cap at dur_ms (500)
    store.toggle_loop()
    assert store.state.loop is False
    store._play_start_time = time.monotonic() - 1.2
    store.tick()
    assert int(store.state.position_ms) == 500

    store.stop()


def test_audio_transport_store_listener_exception_does_not_crash():
    store = AudioTransportStore()
    healthy_received = []

    def broken_listener(_):
        raise RuntimeError("simulated UI subscriber failure")

    def healthy_listener(s):
        healthy_received.append(s)

    store.subscribe(broken_listener)
    store.subscribe(healthy_listener)

    # Dispatching an action triggers _notify_listeners
    store.toggle_auto_play()

    assert len(healthy_received) == 1
    assert healthy_received[0].auto_play is False
