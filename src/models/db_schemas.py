def get_table_schema(table_name: str, version: int) -> list[tuple[str, str]] | None:
    """Retrieves column definitions (name, type) for a given table name and version."""
    clean_name = table_name.lower()
    if clean_name.endswith(".tsv"):
        clean_name = clean_name[:-4]
    if not clean_name.endswith("_tables"):
        clean_name = f"{clean_name}_tables"

    # Direct match
    schema = TABLE_SCHEMAS.get((clean_name, version))
    if schema is not None:
        return schema

    # Fallback to latest known version if exact version is missing
    candidates = [(v, s) for (t, v), s in TABLE_SCHEMAS.items() if t == clean_name]
    if candidates:
        candidates.sort(key=lambda x: x[0], reverse=True)
        return candidates[0][1]

    return None
