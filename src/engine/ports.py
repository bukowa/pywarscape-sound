"""
Abstract boundary ports for Engine layer decoupling (Layer 2).
Defines protocols for workspace project models and layered asset resolution.
"""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path
from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class AssetResolverPort(Protocol):
    """Protocol for layered virtual asset resolution across project overlay, dependencies, and cache."""

    def is_bank_modified(self, bank_name: str) -> bool: ...

    def is_wem_modified(self, wem_id: int | str) -> bool: ...

    def resolve_bank_path(self, bank_name: str) -> Path | None: ...

    def resolve_baseline_bank_path(self, bank_name: str) -> Path | None: ...

    def resolve_baseline_bank_bytes(self, bank_name: str) -> bytes | None: ...

    def resolve_bank_bytes(self, bank_name: str) -> bytes | None: ...

    def resolve_bank_path_by_id(self, bank_id: int) -> Path | None: ...

    def resolve_bank_bytes_by_id(self, bank_id: int) -> bytes | None: ...

    def resolve_wem_path(self, wem_id: int | str) -> Path | None: ...

    def resolve_wem_bytes(self, wem_id: int | str) -> bytes | None: ...

    def resolve_database_path(self) -> Path | None: ...

    def resolve_database_bytes(self) -> bytes | None: ...


@runtime_checkable
class AudioProjectPort(Protocol):
    """Protocol representing an active audio project workspace."""

    @property
    def audio_dir(self) -> Path: ...

    @property
    def source_audio_dir(self) -> Path: ...

    @property
    def manifest_path(self) -> Path: ...

    @property
    def manifest(self) -> Any: ...

    @property
    def cache(self) -> Any: ...

    @property
    def resolver(self) -> AssetResolverPort: ...

    def stage_source_audio(self, src_path: Path | str, wem_id: int) -> str | Path: ...

    def stage_wem(self, wem_id: int | str, data: bytes) -> Path: ...

    def save_bank(self, bank_name: str, data: bytes) -> Path: ...

    def revert_bank(self, bank_name: str) -> bool | None: ...

    def revert_bank_completely(
        self,
        bank_name: str,
        all_banks_media_provider: Callable[[str], frozenset[int]] | None = None,
    ) -> tuple[int, int]: ...

    def revert_wem(self, wem_id: int | str) -> bool | None: ...

    def revert_wem_completely(self, wem_id: int | str) -> bool: ...

    def compile_mod_pack(
        self,
        output_path: Path | str | None = None,
        pack_type: int = 3,
        *,
        validate: bool = False,
    ) -> Path: ...

    def register_in_user_script(self, pack_name: str | None = None) -> Path | None: ...

    def load_metadata_catalog(self) -> Any: ...
